export function wnUIFull(text, lang) {
    if (typeof text !== "string" || !text) return text;
    const zh = (lang || "zh") === "zh";
    const exact = wnUI(text, lang);
    if (exact !== text) return exact;
    for (const [pattern, tpl] of (zh ? WN_DYN2_ZH : WN_DYN2_EN)) {
        const m = new RegExp(pattern).exec(text);
        if (m) return tpl.replace(/\$(\d)/g, (_, i) => m[+i] ?? "");
    }
    let out = text;
    for (const [re, tpl] of (zh ? WN_FRAG_ZH : WN_FRAG_EN)) {
        re.lastIndex = 0;
        out = out.replace(re, tpl);
    }
    return out;
}

