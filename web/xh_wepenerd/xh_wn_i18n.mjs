export function isWNNode(type) {
    return typeof type === "string" && (type.startsWith("XH_WN_") || type.startsWith("XH_QwenEdit") || type.startsWith("XH_WepeNerd"));
}

/** 返回该语言下的显示文案；查不到时：中文态返回 null（回落家族表/原名），EN 态返回英文原名（保证能切回去）。 */
export function wnText(kind, name, lang) {
    if (!name) return null;
    const zh = (lang || "zh") === "zh";
    let m = /^anchor_(\d+)$/.exec(name);
    if (m && kind === "slots") return zh ? `锚点 ${m[1]}` : `Anchor ${m[1]}`;
    m = /^edited_anchor_(\d+)$/.exec(name);
    if (m) return zh ? `改后锚点 ${m[1]}` : `Edited Anchor ${m[1]}`;
    const table = kind === "nodes" ? (zh ? WN_NODES_ZH : WN_NODES_EN)
                : kind === "widgets" ? (zh ? WN_WIDGETS_ZH : null)
                : kind === "slots" ? (zh ? WN_SLOTS_ZH : null) : null;
    if (table && table[name]) return table[name];
    return kind === "nodes" || zh ? null : name;
}

